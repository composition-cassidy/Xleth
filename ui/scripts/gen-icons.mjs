const here = dirname(fileURLToPath(import.meta.url));
// The package's "exports" map hides package.json and the assets, so read them from node_modules.
const core = join(here, '..', 'node_modules', '@phosphor-icons', 'core');
const version = JSON.parse(readFileSync(join(core, 'package.json'), 'utf8')).version;

function pathOf(file) {
  const svg = readFileSync(file, 'utf8').trim();
  // A few Fill assets are 2-3 <path>s; all are plain fills, so their d strings join into one path.
  const m = svg.match(/^<svg[^>]*viewBox="0 0 256 256"[^>]*>((?:<path d="[^"]+"\/>)+)<\/svg>$/);
  if (!m) throw new Error(`${file}: expected only <path> elements on the 256 grid`);
  return [...m[1].matchAll(/d="([^"]+)"/g)].map((x) => x[1]).join('');
}

const lines = [...new Set(ICONS)].sort().map((name) => {
  const r = pathOf(join(core, 'assets', 'regular', `${name}.svg`));
  const f = pathOf(join(core, 'assets', 'fill', `${name}-fill.svg`));
  return `  '${name}': ['${r}', '${f}'],`;
});

const out = `// GENERATED by scripts/gen-icons.mjs from @phosphor-icons/core@${version} (MIT). Do not edit.
// Each entry: [Regular path, Fill path], both on the 256 grid, fill="currentColor".
export const PHOSPHOR = {
${lines.join('\n')}
} as const;

export type PhosphorName = keyof typeof PHOSPHOR;
`;
writeFileSync(join(here, '..', 'src', 'ui-kit', 'icons', 'phosphor.generated.ts'), out);
console.log(`wrote ${lines.length} icons from @phosphor-icons/core@${version}`);
