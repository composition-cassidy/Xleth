#!/usr/bin/env python3
"""Regenerates engine/src/audio/MetronomeSamples.cpp from three click WAVs.

    python -I tools/gen_metronome_samples.py bump.wav hat.wav rim.wav

The clicks are embedded in the engine binary (as mono 16-bit PCM) so the
metronome has no runtime file dependency and nothing to ship in extraResources.
Stereo input is folded to mono; the source files are dual-mono.
"""
import struct
import sys
import wave
from pathlib import Path

NAMES = ["Bump", "Hat", "Rim"]


def load(path):
    with wave.open(path, "rb") as w:
        if w.getsampwidth() != 2:
            raise SystemExit(f"{path}: expected 16-bit PCM")
        ch, rate, n = w.getnchannels(), w.getframerate(), w.getnframes()
        raw = w.readframes(n)
    s = struct.unpack(f"<{n * ch}h", raw)
    mono = [round(sum(s[i * ch:(i + 1) * ch]) / ch) for i in range(n)]
    return mono, rate


def main():
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    out = [
        "// GENERATED by tools/gen_metronome_samples.py - do not edit by hand.",
        "// Click samples: original work by Krasen, licensed under the project license (AGPL-3.0-or-later).",
        '#include "Metronome.h"',
        "",
        "namespace xleth::metronome_data {",
        "",
    ]
    for name, path in zip(NAMES, sys.argv[1:]):
        mono, rate = load(path)
        out.append(f"// {Path(path).name}: {len(mono)} frames @ {rate} Hz, mono 16-bit")
        out.append(f"static const int16_t k{name}[] = {{")
        for i in range(0, len(mono), 16):
            out.append("    " + ", ".join(str(v) for v in mono[i:i + 16]) + ",")
        out.append("};")
        out.append(f"const ClickData g{name} = {{ k{name}, {len(mono)}, {rate} }};")
        out.append("")
    out.append("} // namespace xleth::metronome_data")
    dest = Path(__file__).resolve().parent.parent / "engine/src/audio/MetronomeSamples.cpp"
    dest.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print("wrote", dest)


if __name__ == "__main__":
    main()
