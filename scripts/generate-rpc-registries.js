'use strict';
//
// scripts/generate-rpc-registries.js — emits the two generated C++ name tables
// from ui/rpc-manifest.js (AUDIT.md S1):
//
//   bridge/src/XlethRpcExports.inc   — X-macro list expanded in XlethAddon.cpp::Init()
//   engine/src/XlethRpcDispatch.inc  — X-macro list expanded in XlethEngineService::dispatch()
//
// Both files are checked in so the C++ builds need no CMake↔Node coupling.
// Staleness is enforced by bridge/test_rpc_manifest.js, which runs this script
// with --check (regenerate in memory, byte-compare, exit 1 on drift).
//
//   node scripts/generate-rpc-registries.js          # write both files
//   node scripts/generate-rpc-registries.js --check  # verify, write nothing
//

const fs = require('fs');
const path = require('path');

const repoRoot = path.resolve(__dirname, '..');
const { METHODS, validateManifest } = require(path.join(repoRoot, 'ui', 'rpc-manifest.js'));

validateManifest();

// Generated files are compiled by MSVC — keep them pure ASCII.
const HEADER = (regenNote) =>
  `// GENERATED by scripts/generate-rpc-registries.js from ui/rpc-manifest.js - DO NOT EDIT.\n` +
  `// Regenerate: node scripts/generate-rpc-registries.js\n` +
  `// ${regenNote}\n`;

const exportsInc =
  HEADER('Expanded in bridge/src/XlethAddon.cpp Init() - one addon export per line.') +
  METHODS.map((m) => `XLETH_RPC_EXPORT("${m.method}")`).join('\n') + '\n';

const dispatchInc =
  HEADER('Expanded in engine/src/XlethEngineService.cpp dispatch() - one dispatch branch per line.') +
  METHODS.map((m) =>
    m.returns === 'void'
      ? `XLETH_RPC_VOID("${m.method}", ${m.handler})`
      : `XLETH_RPC_VALUE("${m.method}", ${m.handler})`
  ).join('\n') + '\n';

const targets = [
  { rel: path.join('bridge', 'src', 'XlethRpcExports.inc'), content: exportsInc },
  { rel: path.join('engine', 'src', 'XlethRpcDispatch.inc'), content: dispatchInc },
];

const checkMode = process.argv.includes('--check');
let stale = 0;

for (const { rel, content } of targets) {
  const abs = path.join(repoRoot, rel);
  // Normalize CRLF so a core.autocrlf checkout doesn't read as drift.
  const existing = fs.existsSync(abs)
    ? fs.readFileSync(abs, 'utf8').replace(/\r\n/g, '\n')
    : null;
  if (checkMode) {
    if (existing !== content) {
      console.error(`STALE: ${rel} does not match ui/rpc-manifest.js — run: node scripts/generate-rpc-registries.js`);
      stale++;
    } else {
      console.log(`OK: ${rel}`);
    }
  } else if (existing === content) {
    console.log(`unchanged: ${rel}`);
  } else {
    fs.writeFileSync(abs, content, 'utf8');
    console.log(`wrote: ${rel}`);
  }
}

process.exit(checkMode && stale > 0 ? 1 : 0);
