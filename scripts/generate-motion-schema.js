'use strict';
//
// scripts/generate-motion-schema.js - emits the engine's copy of the motion
// property schema from the ONE definition, ui/src/motion/motionSchema.json
// (docs/XLETH_MOTION_VIEW_DESIGN.md section 4):
//
//   engine/src/model/MotionSchema.generated.inc  - X-macro lists expanded by
//                                                  engine/src/model/MotionSchema.h
//
// Checked in so the C++ build needs no CMake<->Node coupling (same pattern as
// scripts/generate-rpc-registries.js). Staleness is enforced by
// ui/src/motion/motionSchema.test.js, which calls render() and byte-compares.
//
//   node scripts/generate-motion-schema.js          # write the file
//   node scripts/generate-motion-schema.js --check  # verify, write nothing
//

const fs = require('fs');
const path = require('path');

const repoRoot = path.resolve(__dirname, '..');
const SCHEMA_PATH = path.join(repoRoot, 'ui', 'src', 'motion', 'motionSchema.json');
const OUT_REL = path.join('engine', 'src', 'model', 'MotionSchema.generated.inc');

const TYPE = { scalar: 'Scalar', enum: 'Enum', bool: 'Bool', shape: 'Shape', motionBlur: 'MotionBlur', color: 'Color' };
const TIME_BASE = { static: 'Static', event: 'Event', note: 'Note', timeline: 'Timeline' };
const BLEND = { absolute: 'Absolute', multiply: 'Multiply', add: 'Add' };

// MSVC reads the include as the source charset; keep it pure ASCII.
function cstr(s) {
  let out = '"';
  for (const ch of String(s)) {
    const c = ch.codePointAt(0);
    if (ch === '"' || ch === '\\') out += '\\' + ch;
    else if (c >= 0x20 && c < 0x7f) out += ch;
    else throw new Error(`non-ASCII character in schema string: ${JSON.stringify(s)}`);
  }
  return out + '"';
}

function num(v) {
  if (typeof v !== 'number' || !Number.isFinite(v)) throw new Error(`not a finite number: ${v}`);
  const s = String(v);
  return /[.eE]/.test(s) ? s : s + '.0';
}

function validate(schema) {
  const ids = new Set();
  const groups = new Set(schema.groups.map((g) => g.id));
  for (const p of schema.properties) {
    if (ids.has(p.id)) throw new Error(`duplicate property id ${p.id}`);
    ids.add(p.id);
    if (!groups.has(p.group)) throw new Error(`${p.id}: unknown group ${p.group}`);
    if (!TYPE[p.type]) throw new Error(`${p.id}: unknown type ${p.type}`);
    if (!TIME_BASE[p.timeBase]) throw new Error(`${p.id}: unknown timeBase ${p.timeBase}`);
    if (p.type === 'scalar') {
      if (!schema.units[p.unit]) throw new Error(`${p.id}: unknown unit ${p.unit}`);
      if (!BLEND[p.blend]) throw new Error(`${p.id}: unknown blend ${p.blend}`);
      if (!Array.isArray(p.range) || p.range.length !== 2) throw new Error(`${p.id}: range`);
      if (p.clamp !== null && (!Array.isArray(p.clamp) || p.clamp.length !== 2)) throw new Error(`${p.id}: clamp`);
      if (!Number.isInteger(p.engineIndex)) throw new Error(`${p.id}: engineIndex`);
    }
    if (p.type === 'enum' || p.type === 'shape') {
      if (!Array.isArray(p.options) || !p.options.includes(p.identity)) throw new Error(`${p.id}: options/identity`);
    }
  }
}

function render(schema) {
  validate(schema);
  const lines = [];
  lines.push('// GENERATED by scripts/generate-motion-schema.js from ui/src/motion/motionSchema.json - DO NOT EDIT.');
  lines.push('// Regenerate: node scripts/generate-motion-schema.js');
  lines.push('// Expanded by engine/src/model/MotionSchema.h. Each macro family is optional:');
  lines.push('// define the ones you need before including, they are #undef-ed at the end.');
  lines.push('');
  lines.push('#ifndef XLETH_MOTION_SCHEMA_VERSION');
  lines.push('#define XLETH_MOTION_SCHEMA_VERSION(v)');
  lines.push('#endif');
  lines.push('#ifndef XLETH_MOTION_PROP');
  lines.push('#define XLETH_MOTION_PROP(id, group, owner, channel, label, type, unit, identity, rangeLo, rangeHi, hasClamp, clampLo, clampHi, logScale, animatable, timeBase, blend, engineIndex)');
  lines.push('#endif');
  lines.push('#ifndef XLETH_MOTION_OPTION');
  lines.push('#define XLETH_MOTION_OPTION(propId, index, name)');
  lines.push('#endif');
  lines.push('#ifndef XLETH_MOTION_LIMIT');
  lines.push('#define XLETH_MOTION_LIMIT(name, value)');
  lines.push('#endif');
  lines.push('');
  lines.push(`XLETH_MOTION_SCHEMA_VERSION(${schema.version})`);
  lines.push('');
  for (const p of schema.properties) {
    let identity = 0;
    if (p.type === 'scalar') identity = p.identity;
    else if (p.type === 'enum' || p.type === 'shape') identity = p.options.indexOf(p.identity);
    else if (p.type === 'bool') identity = p.identity ? 1 : 0;
    const scalar = p.type === 'scalar';
    const range = scalar ? p.range : [0, 0];
    const hasClamp = scalar && p.clamp !== null;
    const clamp = hasClamp ? p.clamp : [0, 0];
    lines.push(
      'XLETH_MOTION_PROP(' + [
        cstr(p.id), cstr(p.group), cstr(p.owner), cstr(p.channel), cstr(p.label),
        TYPE[p.type], cstr(scalar ? p.unit : ''), num(identity),
        num(range[0]), num(range[1]), hasClamp ? 'true' : 'false', num(clamp[0]), num(clamp[1]),
        p.log ? 'true' : 'false', p.animatable ? 'true' : 'false',
        TIME_BASE[p.timeBase], scalar ? BLEND[p.blend] : (p.blend ? BLEND[p.blend] : 'Absolute'),
        scalar ? String(p.engineIndex) : '-1',
      ].join(', ') + ')');
  }
  lines.push('');
  for (const p of schema.properties) {
    if (!Array.isArray(p.options)) continue;
    p.options.forEach((o, i) => lines.push(`XLETH_MOTION_OPTION(${cstr(p.id)}, ${i}, ${cstr(o)})`));
  }
  lines.push('');
  for (const [k, v] of Object.entries(schema.limits)) {
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(k) || !Number.isInteger(v)) throw new Error(`bad limit ${k}`);
    lines.push(`XLETH_MOTION_LIMIT(${k}, ${v})`);
  }
  lines.push('');
  lines.push('#undef XLETH_MOTION_SCHEMA_VERSION');
  lines.push('#undef XLETH_MOTION_PROP');
  lines.push('#undef XLETH_MOTION_OPTION');
  lines.push('#undef XLETH_MOTION_LIMIT');
  return lines.join('\n') + '\n';
}

function loadSchema() {
  return JSON.parse(fs.readFileSync(SCHEMA_PATH, 'utf8'));
}

module.exports = { render, loadSchema, OUT_REL, SCHEMA_PATH };

if (require.main === module) {
  const content = render(loadSchema());
  const abs = path.join(repoRoot, OUT_REL);
  const existing = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8').replace(/\r\n/g, '\n') : null;
  if (process.argv.includes('--check')) {
    if (existing !== content) {
      console.error(`STALE: ${OUT_REL} does not match ui/src/motion/motionSchema.json - run: node scripts/generate-motion-schema.js`);
      process.exit(1);
    }
    console.log(`OK: ${OUT_REL}`);
  } else if (existing === content) {
    console.log(`unchanged: ${OUT_REL}`);
  } else {
    fs.writeFileSync(abs, content, 'utf8');
    console.log(`wrote: ${OUT_REL}`);
  }
}
